/**
 * The named sections of the home page, in the order they appear.
 *
 * Every section is one record of the "Секција" model in DatoCMS, picked by
 * its key (the "Кључ секције" dropdown). If a section's record does not exist
 * in DatoCMS (or DatoCMS is not connected), the text below — taken from the
 * original design — is shown instead.
 *
 * `nav` is the label in the top menu (null = not in the menu).
 */

export interface SectionItem {
  title: string;
  /** markdown, optional */
  text: string;
}

export interface Section {
  key: SectionKey;
  kicker: string;
  title: string;
  subtitle: string;
  /** markdown */
  text: string;
  items: SectionItem[];
  /** markdown */
  note: string;
  buttonLabel: string;
  buttonLink: string;
  visible: boolean;
}

